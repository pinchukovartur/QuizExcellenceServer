from django.db import models


class ActivityDay(models.Model):
    """Один день, в который игрок прошёл хотя бы одну новую тему.

    Клиент шлёт престиж только при первом прохождении ступени
    (lib/panels/topics_panel.dart), поэтому запись здесь означает
    ровно «в этот день игрок закрыл тему», без правок в приложении.

    Нужна потому, что Prestige хранит только последний updated_at:
    по нему видно, что игрок был активен, но не видно, приходил ли
    он на второй день и на седьмой. Retention без истории дней
    не посчитать, а восстановить её задним числом нельзя.

    Одна строка на игрока в день: таблица растёт как
    (активные игроки) x (дни), а не как число событий.
    """

    game_state_id = models.CharField(max_length=60, db_index=True)
    day = models.DateField(db_index=True)

    # Престиж на конец дня — по нему видно не только «заходил»,
    # но и сколько тем закрыл: активность без прогресса выглядит
    # так же, как активность с прогрессом, если хранить только флаг.
    prestige = models.IntegerField(default=0)

    # День первого прохождения. Дублируется в каждой строке
    # намеренно: иначе на каждый расчёт когорты нужен join
    # с Prestige по 70k строк.
    first_day = models.DateField(db_index=True)

    class Meta:
        # Пара (игрок, день) уникальна — второе прохождение темы
        # в тот же день не создаёт новую строку, а обновляет престиж.
        unique_together = ('game_state_id', 'day')
        indexes = [models.Index(fields=['first_day', 'day'])]

    def __str__(self):
        return '%s %s' % (self.game_state_id, self.day)
